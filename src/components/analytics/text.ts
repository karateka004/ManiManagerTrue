export type AnT = (key: Key, vars?: Record<string, string | number>) => string

function fill(s: string, vars?: Record<string, string | number>): string {
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? `{${k}}` : String(vars[k]))) : s
}

/** Тексты Аналитики на языке человека. */
export function useAnT(): AnT {
  const en = useStore((s) => s.lang) === 'en'
  return (key, vars) => fill(en ? EN[key] : RU[key], vars)
}

/** «(в) октябре» — предложный падеж месяца (у dayjs его нет); предлог — в самом тексте. */
const MONTH_IN_RU = ['январе', 'феврале', 'марте', 'апреле', 'мае', 'июне', 'июле', 'августе', 'сентябре', 'октябре', 'ноябре', 'декабре']
const MONTH_EN = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
export function monthIn(lang: string, monthIndex: number): string {
  return (lang === 'en' ? MONTH_EN : MONTH_IN_RU)[monthIndex]
}

const MONTH_SHORT_RU = ['янв', 'фев', 'мар', 'апр', 'май', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек']
const MONTH_SHORT_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

/** Короткое название месяца без точки: «авг», «Aug». */
export function monthShort(lang: string, monthIndex: number): string {
  return (lang === 'en' ? MONTH_SHORT_EN : MONTH_SHORT_RU)[monthIndex]
}
