/**
 * Ограничитель частоты — счётчики в памяти изолята.
 *
 * Раньше счётчик жил в KV: get и put на КАЖДЫЙ охраняемый запрос. Он съедал
 * записи KV быстрее, чем полезная работа: проверка входящих бота при каждом
 * запуске приложения писала в KV, даже когда входящих не было, а каждое
 * сообщение боту стоило две записи одних только счётчиков. И когда запись
 * падала (квота, перегрузка ключа), падал не ограничитель, а запрос, который он
 * охранял: синхронизация, рейтинг, бот.
 *
 * Память изолята не общая для всех узлов Cloudflare, поэтому лимит здесь —
 * защита от спама и случайных циклов, а не точный учёт. Большего и не нужно:
 * подделать пользователя нельзя (initData подписан, вебхук закрыт секретом), а
 * писать боту быстрее, чем позволяет сам Telegram, человек не может. Точный
 * потолок расходов на модель ставится там, где за неё платят, — квотой проекта в
 * Google Cloud.
 *
 * Fail-open: любая ошибка внутри — запрос пропускаем. Ограничитель существует
 * ради сохранности сервиса, и ронять сервис ради него — худший из исходов.
 */
import type { Env } from './env'

interface Bucket {
  count: number
  resetAt: number
}

const buckets = new Map<string, Bucket>()

/**
 * Потолок числа счётчиков в памяти. Изолят живёт недолго и обслуживает часть
 * пользователей, так что до него дело почти не доходит, — но память не должна
 * расти без предела, если изолят вдруг проживёт сутки на большом потоке.
 */
const MAX_BUCKETS = 20_000

function sweep(now: number): void {
  if (buckets.size < MAX_BUCKETS) return
  for (const [key, b] of buckets) if (b.resetAt <= now) buckets.delete(key)
  // Всё ещё переполнено (все окна живые) — сбрасываем целиком: лучше на минуту
  // забыть счётчики, чем раздуть память изолята.
  if (buckets.size >= MAX_BUCKETS) buckets.clear()
}

/**
 * true, если лимит уже превышен. Окно фиксированное: `limit` запросов за
 * `ttlSec` секунд с момента первого из них.
 *
 * Сигнатура (async, env первым) сохранена прежней, чтобы не трогать шестнадцать
 * мест вызова: смена хранилища — дело этого модуля, а не всех обработчиков.
 */
export async function isRateLimited(
  _env: Env,
  scope: string,
  id: string | number,
  limit: number,
  ttlSec: number,
): Promise<boolean> {
  try {
    const now = Date.now()
    const key = `${scope}:${id}`
    const b = buckets.get(key)
    if (!b || b.resetAt <= now) {
      sweep(now)
      buckets.set(key, { count: 1, resetAt: now + ttlSec * 1000 })
      return false
    }
    if (b.count >= limit) return true
    b.count++
    return false
  } catch {
    return false
  }
}
